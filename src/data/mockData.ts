export type MeetingType = "Пленарное" | "Комитет" | "Совещание";
export type MeetingPriority = "Обычное" | "Важное" | "Срочное";
export type MeetingStatus = "Запланировано" | "Завершено" | "Отменено";
export type DecisionStatus =
  | "Принято"
  | "На исполнении"
  | "Исполнено"
  | "Отложено";

export interface AgendaItem {
  title: string;
  result: string;
  status: "Предстоит" | "Рассмотрено" | "Перенесено";
}
export interface Meeting {
  id: string;
  number: string;
  title: string;
  date: string;
  time: string;
  duration: number;
  type: MeetingType;
  priority: MeetingPriority;
  status: MeetingStatus;
  participants: number | null;
  expectedParticipants: number | null;
  published?: boolean;
  summary: string;
  agenda: AgendaItem[];
  decisions: string[];
}
export interface Decision {
  id: string;
  number: string;
  title: string;
  date: string;
  meetingId: string;
  status: DecisionStatus;
  description: string;
  published?: boolean;
}


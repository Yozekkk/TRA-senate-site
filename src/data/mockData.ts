const moscowDateParts = Object.fromEntries(new Intl.DateTimeFormat("en-US", {
  timeZone: "Europe/Moscow", year: "numeric", month: "2-digit", day: "2-digit",
}).formatToParts(new Date()).map((part) => [part.type, part.value]));
export const TODAY_MSK = `${moscowDateParts.year}-${moscowDateParts.month}-${moscowDateParts.day}`;
export const dateValue = (date: string) => new Date(`${date}T12:00:00Z`);
export const formatDate = (
  date: string,
  options: Intl.DateTimeFormatOptions = {
    day: "numeric",
    month: "long",
    year: "numeric",
  },
) =>
  new Intl.DateTimeFormat("ru-RU", { timeZone: "UTC", ...options }).format(
    dateValue(date),
  );
export const formatShortDate = (date: string) =>
  formatDate(date, { day: "numeric", month: "short" });
export const getMeeting = (id: string) =>
  meetings.find((meeting) => meeting.id === id);
